#!/usr/bin/env python3
"""Builds the launcher icon layers from design/ante-meridiem-icon.svg (the "Ante Merediem.svg" drawing).

The 1280x1280 artboard is mapped onto the 72dp adaptive-icon viewport inside the 108dp canvas.
- ic_launcher_foreground.xml keeps the colours of the drawing.
- ic_launcher_monochrome.xml (themed icons) is a single colour; what the drawing paints in the icon background
  colour (the beige inside the hands) becomes a hole, so the hands keep their look.
Filters (the soft drop shadows) have no vector drawable equivalent and are left out.
Only what the drawing uses is supported: <g>, <path> without transform, <rect> with rotate()/matrix()/translate().
"""
import math
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SVG = ROOT / "design" / "ante-meridiem-icon.svg"
RES = ROOT / "app" / "src" / "main" / "res" / "drawable"
BACKGROUND = "#FFCCBC"  # @color/ic_launcher_background
NS = "{http://www.w3.org/2000/svg}"
K = 0.5522847498
NAMED = {"black": "#000000", "white": "#FFFFFF", "red": "#FF0000"}


def mul(m, t):
    a, b, c, d, e, f = m
    A, B, C, D, E, F = t
    return [a * A + c * B, b * A + d * B, a * C + c * D, b * C + d * D, a * E + c * F + e, b * E + d * F + f]


def matrix(transform):
    m = [1, 0, 0, 1, 0, 0]
    if not transform:
        return m
    for name, args in re.findall(r"(\w+)\s*\(([^)]*)\)", transform):
        v = [float(x) for x in re.split(r"[\s,]+", args.strip()) if x]
        if name == "matrix":
            t = v
        elif name == "translate":
            t = [1, 0, 0, 1, v[0], v[1] if len(v) > 1 else 0]
        elif name == "rotate":
            a = math.radians(v[0])
            c, s = math.cos(a), math.sin(a)
            cx, cy = (v[1], v[2]) if len(v) == 3 else (0, 0)
            t = [c, s, -s, c, cx - c * cx + s * cy, cy - s * cx - c * cy]
        elif name == "scale":
            t = [v[0], 0, 0, v[1] if len(v) > 1 else v[0], 0, 0]
        else:
            raise SystemExit("unsupported transform: " + name)
        m = mul(m, t)
    return m


def apply(m, p):
    x, y = p
    return (m[0] * x + m[2] * y + m[4], m[1] * x + m[3] * y + m[5])


def rounded_rect(x, y, w, h, r):
    r = min(r, w / 2, h / 2)
    k = K * r
    return [("M", [(x + r, y)]), ("L", [(x + w - r, y)]),
            ("C", [(x + w - r + k, y), (x + w, y + r - k), (x + w, y + r)]),
            ("L", [(x + w, y + h - r)]),
            ("C", [(x + w, y + h - r + k), (x + w - r + k, y + h), (x + w - r, y + h)]),
            ("L", [(x + r, y + h)]),
            ("C", [(x + r - k, y + h), (x, y + h - r + k), (x, y + h - r)]),
            ("L", [(x, y + r)]),
            ("C", [(x, y + r - k), (x + r - k, y), (x + r, y)])]


def nodes(segs):
    return [segs[0][1][0]] + [ps[-1] for _, ps in segs[1:]]


def area(segs):
    pts = nodes(segs)
    return sum(x0 * y1 - x1 * y0 for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1])) / 2


def reverse(segs):
    pts = nodes(segs)
    out = [("M", [pts[-1]])]
    for i in range(len(segs) - 1, 0, -1):
        cmd, ps = segs[i]
        out.append(("C", [ps[1], ps[0], pts[i - 1]]) if cmd == "C" else ("L", [pts[i - 1]]))
    return out


def fmt(v):
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def data(segs):
    return "".join(cmd + " ".join(f"{fmt(x)},{fmt(y)}" for x, y in ps) for cmd, ps in segs) + "Z"


def colour(value):
    value = NAMED.get(value.lower(), value) if value else "#000000"
    return "#FF" + value.lstrip("#").upper()


def collect(element, m, fill, group, out):
    """Flat list of (group, colour, segments or None, raw path data or None)."""
    for child in element:
        tag = child.tag.replace(NS, "")
        cm = mul(m, matrix(child.get("transform")))
        f = child.get("fill", fill)
        if tag == "g":
            collect(child, cm, f, len(out) if group is None else group, out)
            continue
        if tag == "rect":
            x, y = float(child.get("x", 0)), float(child.get("y", 0))
            w, h = float(child.get("width")), float(child.get("height"))
            r = float(child.get("rx", child.get("ry", 0)))
            segs = [(cmd, [apply(cm, p) for p in ps]) for cmd, ps in rounded_rect(x, y, w, h, r)]
            out.append((group, f, segs, None))
        elif tag == "path":
            if child.get("transform"):
                raise SystemExit("paths with a transform are not supported")
            out.append((group, f, None, child.get("d")))
        elif tag in ("defs", "filter", "title", "desc"):
            continue
        else:
            raise SystemExit("unsupported element: " + tag)


HEAD = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/prepare_icon.py from design/ante-meridiem-icon.svg: the 1280x1280 artboard mapped onto the
     72dp adaptive-icon viewport. {note} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:translateX="18"
        android:translateY="18"
        android:scaleX="0.05625"
        android:scaleY="0.05625">
        <clip-path android:pathData="M0,0H1280V1280H0Z" />
"""
TAIL = """    </group>
</vector>
"""


def path(fill, d, indent="        "):
    return f'{indent}<path android:fillColor="{fill}"\n{indent}    android:pathData="{d}" />\n'


def main():
    root = ET.parse(SVG).getroot()
    items = []
    collect(root, [1, 0, 0, 1, 0, 0], None, None, items)
    fg = HEAD.format(note="Shadows left out.")
    for _, f, segs, raw in items:
        fg += path(colour(f), data(segs) if segs else raw)
    (RES / "ic_launcher_foreground.xml").write_text(fg + TAIL, encoding="utf-8")

    mono = HEAD.format(note="One colour; the beige of the drawing is cut out.")
    groups = []
    for g, _, _, _ in items:
        if g not in groups:
            groups.append(g)
    for g in groups:
        mine = [i for i in items if i[0] == g]
        holes = [i for i in mine if colour(i[1]) == colour(BACKGROUND) and i[2]]
        solid = [i for i in mine if colour(i[1]) != colour(BACKGROUND)]
        indent = "        "
        if holes:
            clip = "M-10,-10H1290V1290H-10Z"
            for _, _, segs, _ in holes:
                clip += data(reverse(segs) if area(segs) > 0 else segs)
            mono += f'{indent}<group>\n{indent}    <clip-path android:pathData="{clip}" />\n'
            indent += "    "
        for _, _, segs, raw in solid:
            mono += path("#FFFFFFFF", data(segs) if segs else raw, indent)
        if holes:
            mono += "        </group>\n"
    (RES / "ic_launcher_monochrome.xml").write_text(mono + TAIL, encoding="utf-8")
    print(f"{len(items)} shapes, {sum(1 for g in groups if g is not None)} groups")


if __name__ == "__main__":
    main()